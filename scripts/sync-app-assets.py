#!/usr/bin/env python3
"""Export canonical iOS assets. Usage: python3 scripts/sync-app-assets.py [app-repo]

Requires PyMuPDF. PDF icons remain vectors; illustrations render at 2x with alpha.
"""

import hashlib
import json
from pathlib import Path
import shutil
import sys
import struct

import fitz


WEB = Path(__file__).resolve().parents[1]
APP = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else WEB.parent / "Newdok"
ASSETS = APP / "Modules/DesignSystem/Resources/Assets.xcassets"
ICONS = {"font", "highlight", "pen", "trashbin", "bookmarked", "kakaoBubble", "darklogo", "check", "uncheck"}
ILLUSTRATIONS = {"letter", "calendar", "post", "signup", "nologin", "nodata", "nosubscribe", "emptybookmark", "noprofile", "nohighlight", "warning"}
manifest = []

for imageset in sorted(ASSETS.rglob("*.imageset")):
    name = imageset.stem
    is_icon = name.startswith(("Line ", "Fill ", "_Line ")) or name == "Back"
    if not is_icon and name not in ICONS | ILLUSTRATIONS | {"logo"}:
        continue
    contents = json.loads((imageset / "Contents.json").read_text())
    filenames = [image["filename"] for image in contents["images"] if image.get("filename")]
    source = imageset / filenames[-1]
    target = WEB / "public/images" / (f"{name}.svg" if is_icon else f"app/{'home-logo' if name == 'logo' else name}.{'png' if name in ILLUSTRATIONS or name == 'logo' else 'svg'}")
    target.parent.mkdir(parents=True, exist_ok=True)
    if source.suffix == ".pdf":
        with fitz.open(source) as document:
            if target.suffix == ".svg":
                target.write_text(document[0].get_svg_image())
            else:
                document[0].get_pixmap(matrix=fitz.Matrix(2, 2), alpha=True).save(target)
    else:
        shutil.copyfile(source, target)
    if target.suffix == '.png':
        width, height = struct.unpack('>II', target.read_bytes()[16:24])
    else:
        with fitz.open(source) as document:
            width, height = document[0].rect.width, document[0].rect.height
    manifest.append({
        "asset": name,
        "source": str(source.relative_to(APP)),
        "sourceSha256": hashlib.sha256(source.read_bytes()).hexdigest(),
        "output": str(target.relative_to(WEB / "public")),
        "outputSha256": hashlib.sha256(target.read_bytes()).hexdigest(),
        "width": width,
        "height": height,
    })

(WEB / "public/images/app/manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")
icons = {item['asset']: '/' + item['output'] for item in manifest if item['asset'].startswith(('Line ', '_Line ')) or item['asset'] in {'Back', 'font', 'highlight', 'pen', 'trashbin'}}
images = {item['asset']: {key: item[key] for key in ('width', 'height')} | {'src': '/' + item['output']} for item in manifest if item['asset'] not in icons}
(WEB / 'src/design-system/assets.ts').write_text('// Generated by scripts/sync-app-assets.py from the iOS asset catalog.\nexport const iconAssets = ' + json.dumps(icons, ensure_ascii=False, indent=2) + ' as const;\n\nexport const imageAssets = ' + json.dumps(images, ensure_ascii=False, indent=2) + ' as const;\n\nexport type IconName = keyof typeof iconAssets;\nexport type ImageName = keyof typeof imageAssets;\n')
print(f"Synced {len(manifest)} app assets")
